#!/usr/bin/env python3
"""Generate core/src/protocol_gen.zig signature tables from protocol/*.xml."""
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
XMLS = [
    ROOT / "protocol" / "wayland.xml",
    ROOT / "protocol" / "xdg-shell.xml",
    ROOT / "protocol" / "xdg-decoration-unstable-v1.xml",
    ROOT / "protocol" / "cursor-shape-v1.xml",
    ROOT / "protocol" / "viewporter.xml",
    ROOT / "protocol" / "fractional-scale-v1.xml",
    ROOT / "protocol" / "text-input-unstable-v3.xml",
    ROOT / "protocol" / "primary-selection-unstable-v1.xml",
    ROOT / "protocol" / "linux-dmabuf-v1.xml",
    ROOT / "protocol" / "relative-pointer-unstable-v1.xml",
    ROOT / "protocol" / "pointer-constraints-unstable-v1.xml",
    ROOT / "protocol" / "presentation-time.xml",
]
OUT = ROOT / "core" / "src" / "protocol_gen.zig"

ARG_MAP = {
    "int": ".int", "uint": ".uint", "fixed": ".fixed", "string": ".string",
    "object": ".object", "array": ".array", "fd": ".fd",
}

def emit_message(m):
    args, new_id_iface = [], None
    for a in m.findall("arg"):
        t = a.get("type")
        if t == "new_id":
            if a.get("interface") is None:
                args.append(".new_id_dynamic")
            else:
                args.append(".new_id")
                new_id_iface = a.get("interface")
        else:
            args.append(ARG_MAP[t])
    iface_field = f' .new_id_interface = "{new_id_iface}",' if new_id_iface else ""
    dtor_field = " .destructor = true," if m.get("type") == "destructor" else ""
    return (f'        .{{ .name = "{m.get("name")}", '
            f'.args = &.{{ {", ".join(args)} }},{iface_field}{dtor_field} }},')

lines = [
    "// SPDX-FileCopyrightText: 2026 Pooya Parsa <pooya@pi0.io>",
    "// SPDX-License-Identifier: MPL-2.0",
    "",
    "//! GENERATED by tools/gen_protocol.py from protocol/*.xml — do not edit.",
    'const wire = @import("wire.zig");',
    "",
    "pub const Message = struct {",
    "    name: []const u8,",
    "    args: []const wire.ArgType,",
    "    /// Interface created by a typed new_id arg, if any.",
    "    new_id_interface: ?[]const u8 = null,",
    "    destructor: bool = false,",
    "};",
    "",
    "pub const Interface = struct {",
    "    name: []const u8,",
    "    version: u32,",
    "    requests: []const Message,",
    "    events: []const Message,",
    "",
    "    pub fn eventIndex(iface: *const Interface, name: []const u8) ?u16 {",
    "        for (iface.events, 0..) |*m, i| {",
    "            if (std.mem.eql(u8, m.name, name)) return @intCast(i);",
    "        }",
    "        return null;",
    "    }",
    "",
    "    pub fn requestIndex(iface: *const Interface, name: []const u8) ?u16 {",
    "        for (iface.requests, 0..) |*m, i| {",
    "            if (std.mem.eql(u8, m.name, name)) return @intCast(i);",
    "        }",
    "        return null;",
    "    }",
    "};",
    "",
    "pub const interfaces = [_]Interface{",
]

for xml in XMLS:
    for iface in ET.parse(xml).getroot().iter("interface"):
        lines.append(f'    .{{ .name = "{iface.get("name")}", .version = {iface.get("version")}, .requests = &.{{')
        for m in iface.findall("request"):
            lines.append(emit_message(m))
        lines.append("    }, .events = &.{")
        for m in iface.findall("event"):
            lines.append(emit_message(m))
        lines.append("    } },")

lines += [
    "};",
    "",
    "pub fn find(name: []const u8) ?*const Interface {",
    "    for (&interfaces) |*iface| {",
    "        if (std.mem.eql(u8, iface.name, name)) return iface;",
    "    }",
    "    return null;",
    "}",
    "",
    'const std = @import("std");',
    "",
]

OUT.write_text("\n".join(lines))
print(f"wrote {OUT} ({len(lines)} lines)", file=sys.stderr)
